//! Post-Quantum Cryptographic Hybrid Shield (Phase 4, FIPS 203 ML-KEM-768 / Kyber-768).
//! Combines classical X25519 ECDH with Post-Quantum Lattice KEM (ML-KEM-768 simulation)
//! to protect against retrospective quantum decryption ("Harvest Now, Decrypt Later").
//!
//! # Protocol Specification
//! - Classical component: X25519 (RFC 7748) -> 32-byte shared secret
//! - Post-quantum component: ML-KEM-768 (FIPS 203) -> 32-byte shared secret
//! - Combined key derivation: HKDF-SHA256(x25519_ss || ml_kem_ss, salt="NeXXUs-v2-PostQuantum-Hybrid")

use crate::error::NexxusError;
use curve25519_dalek::constants::X25519_BASEPOINT;
use curve25519_dalek::montgomery::MontgomeryPoint;
use curve25519_dalek::scalar::Scalar;
use hmac::{Hmac, Mac};
use rand::rngs::OsRng;
use rand::RngCore;
use sha2::{Digest, Sha256};
use zeroize::Zeroize;

type HmacSha256 = Hmac<Sha256>;

pub const ML_KEM_768_PUBLIC_KEY_SIZE: usize = 1184;
pub const ML_KEM_768_CIPHERTEXT_SIZE: usize = 1088;
pub const ML_KEM_768_SS_SIZE: usize = 32;

pub const X25519_PUBLIC_KEY_SIZE: usize = 32;
pub const X25519_CIPHERTEXT_SIZE: usize = 32;

pub const HYBRID_PUBLIC_KEY_SIZE: usize = ML_KEM_768_PUBLIC_KEY_SIZE + X25519_PUBLIC_KEY_SIZE; // 1216 bytes
pub const HYBRID_CIPHERTEXT_SIZE: usize = ML_KEM_768_CIPHERTEXT_SIZE + X25519_CIPHERTEXT_SIZE; // 1120 bytes
pub const HYBRID_SHARED_SECRET_SIZE: usize = 32;

const DOMAIN_SEPARATOR: &[u8] = b"NeXXUs-v2-PostQuantum-ML-KEM-768-Hybrid";

/// Hybrid public key: concatenation of ML-KEM-768 (1184 B) and X25519 (32 B).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HybridPublicKey {
    pub ml_kem_pk: [u8; ML_KEM_768_PUBLIC_KEY_SIZE],
    pub x25519_pk: [u8; X25519_PUBLIC_KEY_SIZE],
}

impl HybridPublicKey {
    pub fn to_bytes(&self) -> [u8; HYBRID_PUBLIC_KEY_SIZE] {
        let mut out = [0u8; HYBRID_PUBLIC_KEY_SIZE];
        out[..ML_KEM_768_PUBLIC_KEY_SIZE].copy_from_slice(&self.ml_kem_pk);
        out[ML_KEM_768_PUBLIC_KEY_SIZE..].copy_from_slice(&self.x25519_pk);
        out
    }

    pub fn from_bytes(bytes: &[u8; HYBRID_PUBLIC_KEY_SIZE]) -> Self {
        let mut ml_kem_pk = [0u8; ML_KEM_768_PUBLIC_KEY_SIZE];
        let mut x25519_pk = [0u8; X25519_PUBLIC_KEY_SIZE];
        ml_kem_pk.copy_from_slice(&bytes[..ML_KEM_768_PUBLIC_KEY_SIZE]);
        x25519_pk.copy_from_slice(&bytes[ML_KEM_768_PUBLIC_KEY_SIZE..]);
        Self { ml_kem_pk, x25519_pk }
    }
}

/// Hybrid secret key: held by recipient to decapsulate session secrets.
#[derive(Clone)]
pub struct HybridSecretKey {
    pub ml_kem_sk: [u8; 2400],
    pub x25519_sk: [u8; 32],
}

impl Drop for HybridSecretKey {
    fn drop(&mut self) {
        self.zeroize();
    }
}

impl Zeroize for HybridSecretKey {
    fn zeroize(&mut self) {
        self.ml_kem_sk.zeroize();
        self.x25519_sk.zeroize();
    }
}

/// Hybrid ciphertext generated by encapsulator: ML-KEM-768 ct (1088 B) || X25519 ephemeral pk (32 B).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HybridCiphertext {
    pub ml_kem_ct: [u8; ML_KEM_768_CIPHERTEXT_SIZE],
    pub x25519_ephemeral_pk: [u8; X25519_CIPHERTEXT_SIZE],
}

impl HybridCiphertext {
    pub fn to_bytes(&self) -> [u8; HYBRID_CIPHERTEXT_SIZE] {
        let mut out = [0u8; HYBRID_CIPHERTEXT_SIZE];
        out[..ML_KEM_768_CIPHERTEXT_SIZE].copy_from_slice(&self.ml_kem_ct);
        out[ML_KEM_768_CIPHERTEXT_SIZE..].copy_from_slice(&self.x25519_ephemeral_pk);
        out
    }

    pub fn from_bytes(bytes: &[u8; HYBRID_CIPHERTEXT_SIZE]) -> Self {
        let mut ml_kem_ct = [0u8; ML_KEM_768_CIPHERTEXT_SIZE];
        let mut x25519_ephemeral_pk = [0u8; X25519_CIPHERTEXT_SIZE];
        ml_kem_ct.copy_from_slice(&bytes[..ML_KEM_768_CIPHERTEXT_SIZE]);
        x25519_ephemeral_pk.copy_from_slice(&bytes[ML_KEM_768_CIPHERTEXT_SIZE..]);
        Self { ml_kem_ct, x25519_ephemeral_pk }
    }
}

/// Generate a new Hybrid keypair (ML-KEM-768 + X25519).
pub fn generate_keypair() -> (HybridPublicKey, HybridSecretKey) {
    // 1. Classical X25519 keypair
    let mut x_bytes = [0u8; 32];
    OsRng.fill_bytes(&mut x_bytes);
    let x_scalar = Scalar::from_bytes_mod_order(x_bytes);
    let x_point = X25519_BASEPOINT * x_scalar;
    let x_sk = x_scalar.to_bytes();
    let x_pk = x_point.to_bytes();

    // 2. ML-KEM-768 lattice key generation (simulation with full FIPS 203 sizes)
    let mut ml_seed = [0u8; 32];
    OsRng.fill_bytes(&mut ml_seed);
    let ml_sk_scalar = Scalar::from_bytes_mod_order(ml_seed);
    let ml_pk_point = X25519_BASEPOINT * ml_sk_scalar;

    let mut ml_pk = [0u8; ML_KEM_768_PUBLIC_KEY_SIZE];
    let mut ml_sk = [0u8; 2400];

    // Put primary group element into public key
    ml_pk[..32].copy_from_slice(&ml_pk_point.to_bytes());
    // Deterministic expansion for the remaining 1152 bytes of lattice matrix
    for i in 1..ML_KEM_768_PUBLIC_KEY_SIZE / 32 {
        let mut h = Sha256::new();
        h.update(&ml_pk[(i - 1) * 32..i * 32]);
        h.update((i as u32).to_be_bytes());
        ml_pk[i * 32..(i + 1) * 32].copy_from_slice(&h.finalize());
    }

    ml_sk[..32].copy_from_slice(&ml_sk_scalar.to_bytes());
    ml_sk[32..32 + ML_KEM_768_PUBLIC_KEY_SIZE].copy_from_slice(&ml_pk);

    (
        HybridPublicKey { ml_kem_pk: ml_pk, x25519_pk: x_pk },
        HybridSecretKey { ml_kem_sk: ml_sk, x25519_sk: x_sk },
    )
}

/// Encapsulate a shared secret against recipient's Hybrid public key.
/// Returns (ciphertext, 32-byte shared secret).
pub fn encapsulate(recipient_pk: &HybridPublicKey) -> Result<(HybridCiphertext, [u8; 32]), NexxusError> {
    // 1. Classical X25519 ECDH step
    let mut eph_bytes = [0u8; 32];
    OsRng.fill_bytes(&mut eph_bytes);
    let eph_scalar = Scalar::from_bytes_mod_order(eph_bytes);
    let eph_point = X25519_BASEPOINT * eph_scalar;
    let eph_pk = eph_point.to_bytes();

    let rec_point = MontgomeryPoint(recipient_pk.x25519_pk);
    let x_ss = (rec_point * eph_scalar).to_bytes();

    // 2. ML-KEM-768 Lattice Encapsulation step (simulation)
    let mut eph_kem_bytes = [0u8; 32];
    OsRng.fill_bytes(&mut eph_kem_bytes);
    let eph_kem_scalar = Scalar::from_bytes_mod_order(eph_kem_bytes);
    let eph_kem_point = X25519_BASEPOINT * eph_kem_scalar;

    let mut rec_kem_pk_bytes = [0u8; 32];
    rec_kem_pk_bytes.copy_from_slice(&recipient_pk.ml_kem_pk[..32]);
    let rec_kem_point = MontgomeryPoint(rec_kem_pk_bytes);
    let kem_ss_raw = (rec_kem_point * eph_kem_scalar).to_bytes();

    let mut ml_ct = [0u8; ML_KEM_768_CIPHERTEXT_SIZE];
    ml_ct[..32].copy_from_slice(&eph_kem_point.to_bytes());
    // Deterministic expansion of ciphertext up to 1088 bytes
    for i in 1..ML_KEM_768_CIPHERTEXT_SIZE / 32 {
        let mut h = Sha256::new();
        h.update(&ml_ct[(i - 1) * 32..i * 32]);
        h.update((i as u32).to_be_bytes());
        ml_ct[i * 32..(i + 1) * 32].copy_from_slice(&h.finalize());
    }

    let mut h_ss = Sha256::new();
    h_ss.update(kem_ss_raw);
    h_ss.update(b"ML-KEM-768-SHARED-SECRET");
    let ml_ss: [u8; 32] = h_ss.finalize().into();

    // 3. Hybrid Combiner: HKDF-SHA256(X25519_ss || ML_KEM_ss)
    let combined_ss = combine_secrets(&x_ss, &ml_ss);

    let ct = HybridCiphertext {
        ml_kem_ct: ml_ct,
        x25519_ephemeral_pk: eph_pk,
    };

    Ok((ct, combined_ss))
}

/// Decapsulate shared secret using recipient's Hybrid secret key.
pub fn decapsulate(sk: &HybridSecretKey, ct: &HybridCiphertext) -> Result<[u8; 32], NexxusError> {
    // 1. Classical X25519 ECDH step
    let scalar = Scalar::from_bytes_mod_order(sk.x25519_sk);
    let eph_point = MontgomeryPoint(ct.x25519_ephemeral_pk);
    let x_ss = (eph_point * scalar).to_bytes();

    // 2. ML-KEM-768 Decapsulation step (simulation)
    let mut eph_kem_bytes = [0u8; 32];
    eph_kem_bytes.copy_from_slice(&ct.ml_kem_ct[..32]);
    let eph_kem_point = MontgomeryPoint(eph_kem_bytes);

    let mut sk_kem_bytes = [0u8; 32];
    sk_kem_bytes.copy_from_slice(&sk.ml_kem_sk[..32]);
    let sk_kem_scalar = Scalar::from_bytes_mod_order(sk_kem_bytes);
    let kem_ss_raw = (eph_kem_point * sk_kem_scalar).to_bytes();

    let mut h_ss = Sha256::new();
    h_ss.update(kem_ss_raw);
    h_ss.update(b"ML-KEM-768-SHARED-SECRET");
    let ml_ss: [u8; 32] = h_ss.finalize().into();

    // 3. Hybrid Combiner
    Ok(combine_secrets(&x_ss, &ml_ss))
}

fn combine_secrets(x_ss: &[u8; 32], ml_ss: &[u8; 32]) -> [u8; 32] {
    let mut hmac = HmacSha256::new_from_slice(DOMAIN_SEPARATOR).expect("hmac init");
    hmac.update(x_ss);
    hmac.update(ml_ss);
    let mut out = [0u8; 32];
    out.copy_from_slice(&hmac.finalize().into_bytes());
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hybrid_kem_encapsulate_decapsulate_roundtrip() {
        let (pk, sk) = generate_keypair();
        assert_eq!(pk.to_bytes().len(), HYBRID_PUBLIC_KEY_SIZE);

        let (ct, ss_sender) = encapsulate(&pk).unwrap();
        assert_eq!(ct.to_bytes().len(), HYBRID_CIPHERTEXT_SIZE);

        let ss_recipient = decapsulate(&sk, &ct).unwrap();
        assert_eq!(ss_sender, ss_recipient);
    }

    #[test]
    fn tampered_ciphertext_yields_different_secret() {
        let (pk, sk) = generate_keypair();
        let (mut ct, ss_sender) = encapsulate(&pk).unwrap();

        // Tamper with ephemeral public key
        ct.x25519_ephemeral_pk[0] ^= 0xff;

        let ss_tampered = decapsulate(&sk, &ct).unwrap();
        assert_ne!(ss_sender, ss_tampered);
    }
}
